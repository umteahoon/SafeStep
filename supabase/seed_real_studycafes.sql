-- ============================================================
-- STEP 0 (먼저 실행, 확인용): "이주환" 관련 학원 지점 찾기
-- 학원 이름 자체에 포함된 경우와, 원장 프로필 이름이 "이주환"인 경우를
-- 모두 찾습니다. 결과에 지우려는 지점이 맞는지 꼭 확인한 뒤 STEP 1로
-- 넘어가세요. 결과가 없거나 더 지워야 할 지점이 있으면 STEP 1을 그에 맞게
-- 수정해서 실행하세요.
-- ============================================================
SELECT
  a.id,
  a.name AS academy_name,
  a.address,
  p.name AS owner_name,
  p.email AS owner_email
FROM academies a
LEFT JOIN profiles p ON p.academy_id = a.id AND p.role = 'ACADEMY_ADMIN'
WHERE a.name ILIKE '%이주환%' OR p.name ILIKE '%이주환%';

-- ============================================================
-- STEP 1: 위 결과를 확인한 뒤 실행 — 이주환 원장 지점 삭제
-- seats/students/classes/chat_rooms 등 academies.id를 참조하는 테이블은
-- ON DELETE CASCADE라 함께 정리됩니다. 원장 프로필(profiles)은 삭제되지
-- 않고 academy_id만 비워져서, 다시 로그인하면 발급코드 입력 화면으로
-- 돌아갑니다.
-- ============================================================
DELETE FROM academies
WHERE id IN (
  SELECT a.id
  FROM academies a
  LEFT JOIN profiles p ON p.academy_id = a.id AND p.role = 'ACADEMY_ADMIN'
  WHERE a.name ILIKE '%이주환%' OR p.name ILIKE '%이주환%'
);

